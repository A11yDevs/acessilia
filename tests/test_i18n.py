def test_the_runtime_reads_the_po_not_a_stale_mo(
    monkeypatch: pytest.MonkeyPatch, tmp_path: Path
) -> None:
    """A ``messages.mo`` left beside the source is not read: only the ``.po``
    is the catalog (review of #569)."""
    import shutil

    from babel.messages.catalog import Catalog
    from babel.messages.mofile import write_mo

    root = tmp_path / "locales"
    shutil.copytree(DEFAULT_REPOS_CATALOGS_DIR, root, ignore=shutil.ignore_patterns("*.mo"))
    stale = Catalog(locale="pt_BR")
    stale.add("Processing your document…", "STALE TRANSLATION")
    with open(root / "pt_BR" / "LC_MESSAGES" / "messages.mo", "wb") as stream:
        write_mo(stream, stale)
    monkeypatch.setattr(i8n, "LOCALE_CATALOGS_DIR", root)
    i8n._catalog_for.cache_clear()
    try:
        assert i8n.get_translations("pt_BR").gettext("Processing your document…") == "Processando seu documento…"
    finally:
        i8n._catalog_for.cache_clear()
