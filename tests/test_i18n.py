"""
What this suite verifies: the runtime translation helper acessilia_core.i18n resolves localized strings and plural
forms from Babel message catalogs generated by scripts/gen_locale_catalogs for the supported locales (en_US,
pt_BR), falls back to canonical English msgids when no catalog or entry is available, negotiates locale selection
from environment variables correctly, and that the checked-in default catalog tree under libs/core/src/acessilia_core/i18n/locales exists.
"""

from __future__ import annotations

from pathlib import Path

import pytest

import acessilia_core.i18n as i8n
import scripts.gen_locale_catalogs as gen_locales
from tests.locale_support import use_server_locale

DEFAULT_REPOS_CATALOGS_DIR: Path = Path("libs/core/src/acessilia_core/i18n/locales")


@pytest.fixture
def catalogs(tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> Path:
    """Build fresh locale catalogs in a per-test directory and point acessilia_core.i18n at that root.

    The root comes from ``tmp_path`` so each test owns its catalog tree: under
    pytest-xdist a single shared root let one worker rewrite ``messages.mo``
    while another read it, which surfaced as ``struct.error`` inside
    ``gettext`` on a truncated file. It also keeps the generated artifacts
    outside the checked-in tree.

    Args:
        tmp_path (Path): Per-test temporary directory supplied by pytest.
        monkeypatch (pytest.MonkeyPatch): Instance used to repoint the runtime catalog directory.

    Returns:
        Path: Root of the catalog tree built for this test.
    """
    root = tmp_path / "locales"
    gen_locales.build_locales(root)
    monkeypatch.setattr(i8n, "LOCALE_CATALOGS_DIR", root)
    i8n._catalog_for.cache_clear()
    return root


