def test_every_web_message_constant_has_a_pt_br_translation() -> None:
    """
    Every WEB_* user-facing constant exported by frontend.web.messages must be
    registered in the generator's TRANSLATIONS table, otherwise it ships as the
    untranslated English msgid to pt_BR users. This is the regression guard for
    exactly what happened to WEB_JOB_CLOSE_INFO: a new constant added to
    messages.py but never to gen_locale_catalogs, which the catalog-drift tests
    could not catch because the msgid was absent from both sides.
    """
    import frontend.web.messages as web_messages

    web_ids = {
        value for name, value in vars(web_messages).items()
        if name.startswith("WEB_") and isinstance(value, str)
    }
    assert web_ids, "frontend.web.messages must export WEB_* message constants"
    pt_br = gen_locales.TRANSLATIONS["pt_BR"]
    missing = sorted(web_ids - set(pt_br))
    assert not missing, (
        "WEB_* constants without a pt_BR entry in gen_locale_catalogs."
        f"TRANSLATIONS: {missing}"
    )


def test_default_checked_in_catalog_tree_is_generated_by_repo_layout(tmp_path: Path) -> None:
    """Check the production location and generate its layout without rewriting tracked catalogs."""
    assert gen_locales.DEFAULT_LOCALES_DIR.resolve() == DEFAULT_REPOS_CATALOGS_DIR.resolve()
    generated_root = tmp_path / "i18n-locales"
    gen_locales.build_locales(generated_root)
    for locale in gen_locales.SUPPORTED_LOCALES:
        assert (DEFAULT_REPOS_CATALOGS_DIR / locale / "LC_MESSAGES" / "messages.po").is_file()
        for extension in ("po", "mo"):
            assert (generated_root / locale / "LC_MESSAGES" / f"messages.{extension}").is_file()
def test_checked_in_catalogs_match_what_the_generator_produces(tmp_path) -> None:
    """The checked-in ``.po`` sources must be exactly what ``build_locales`` writes.

    This used to regenerate straight into ``libs/core/src/acessilia_core/i18n/locales`` and only assert the
    four files existed, so every test run rewrote the checked-in sources and left
    the worktree dirty even when nothing had changed. Comparing content instead
    makes the test a real check and keeps the repository read-only:

    - drift between the message table and the checked-in catalogs now fails, and
      the fix is to rerun ``python -m scripts.gen_locale_catalogs``;
    - the generator has to stay deterministic, which is why
      :data:`gen_locales.CATALOG_CREATION_DATE` is fixed rather than derived from
      the clock.
    """
    generated = gen_locales.build_locales(tmp_path)

    for locale, (po_path, _) in generated.items():
        checked_in = DEFAULT_REPOS_CATALOGS_DIR / locale / "LC_MESSAGES" / "messages.po"
        assert checked_in.is_file(), f"{checked_in} ausente"
        assert po_path.read_bytes() == checked_in.read_bytes(), (
            f"{locale}: libs/core/src/acessilia_core/i18n/locales está defasado em relação à tabela de "
            "mensagens; rode `python -m scripts.gen_locale_catalogs`"
        )


def test_catalog_generation_is_deterministic(tmp_path) -> None:
    """Regenerating twice must produce byte-identical catalogs.

    A clock-derived ``POT-Creation-Date`` made the previously checked-in files
    differ on every run, which is what turned every test run into a source-tree
    modification.
    """
    first = gen_locales.build_locales(tmp_path / "a")
    second = gen_locales.build_locales(tmp_path / "b")

    for locale in first:
        assert first[locale][0].read_bytes() == second[locale][0].read_bytes()
        assert first[locale][1].read_bytes() == second[locale][1].read_bytes()


def test_server_locale_negotiated_from_shell_env() -> None:
    """
    The server-side locale should negotiate from the shell environment the service passes (no LOCALE set): a
    Portuguese shell locale maps to pt_BR, an English one to en_US, and a C/POSIX locale (no translatable language)
    falls back to the C locale's language, then to en_US.
    """
    assert i8n.negotiate_server_locale({"LANG": "pt_BR.UTF-8"}) == "pt_BR"
    assert i8n.negotiate_server_locale({"LANG": "en_US.UTF-8"}) == "en_US"
    assert i8n.negotiate_server_locale({"LANG": "C"}) == "en_US"
    assert i8n.negotiate_server_locale({"LANG": "C"}, "pt_BR") == "pt_BR"
    assert i8n.negotiate_server_locale({"LANGUAGE": "pt_BR:en_US", "LANG": "en_US.UTF-8"}) == "pt_BR"
    assert i8n.negotiate_server_locale({}) == "en_US"


def test_env_locale_value_overrides_shell_locale() -> None:
    """A set LOCALE value (e.g. from .env) takes precedence over the shell environment locale."""
    assert i8n.negotiate_server_locale({"LOCALE": "pt_BR", "LANG": "en_US.UTF-8"}) == "pt_BR"


def test_the_server_locale_is_configured_once(monkeypatch: pytest.MonkeyPatch) -> None:
    """A configured locale stays until configured again, whatever the environment says later; an unsupported
    one falls back to en_US."""
    use_server_locale(monkeypatch, None)
    i8n.configure_server_locale("pt_BR")
    monkeypatch.setenv("LOCALE", "en_US")
    assert i8n._active_locale() == "pt_BR"
    i8n.configure_server_locale("xx_XX")
    assert i8n._active_locale() == "en_US"


def test_locale_for_user_matches_offered_locale(monkeypatch: pytest.MonkeyPatch) -> None:
    """
    Remote users advertising a Portuguese hint (base 'pt', 'pt-BR' or with an encoding tail) should map to the offered
    pt_BR locale; English hints map to en_US; unmatched or absent hints fall back to the server-side locale.
    """
    use_server_locale(monkeypatch, "en_US")
    assert i8n.locale_for_user("pt") == "pt_BR"
    assert i8n.locale_for_user("pt-BR") == "pt_BR"
    assert i8n.locale_for_user("pt_BR.UTF-8") == "pt_BR"
    assert i8n.locale_for_user("en") == "en_US"
    assert i8n.locale_for_user("en-US") == "en_US"
    assert i8n.locale_for_user("es") == "en_US"
    assert i8n.locale_for_user(None) == "en_US"


def test_set_request_locale_overrides_server_locale(monkeypatch: pytest.MonkeyPatch, catalogs: Path) -> None:
    """
    Within a task, set_request_locale should redirect t() to the user locale even when the server locale differs, and
    reset_request_locale should restore the server-side locale afterwards.
    """
    use_server_locale(monkeypatch, "en_US")
    i8n._catalog_for.cache_clear()
    assert i8n.t("Downloading file...") == "Downloading file..."
    token = i8n.set_request_locale("pt_BR")
    i8n._catalog_for.cache_clear()
    assert i8n.t("Downloading file...") == "Baixando arquivo..."
    i8n.reset_request_locale(token)
    i8n._catalog_for.cache_clear()
    assert i8n.t("Downloading file...") == "Downloading file..."


def test_generated_catalogs_preserve_versioned_messages(tmp_path):
    from babel.messages.pofile import read_po
    generated = gen_locales.build_locales(tmp_path)
    for locale, (po_path, _) in generated.items():
        with po_path.open("rb") as stream:
            actual = {msg.id: msg.string for msg in read_po(stream) if msg.id}
        with (DEFAULT_REPOS_CATALOGS_DIR / locale / "LC_MESSAGES/messages.po").open("rb") as stream:
            expected = {msg.id: msg.string for msg in read_po(stream) if msg.id}
        assert actual == expected


